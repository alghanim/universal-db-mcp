CONNECT TO TESTDB;
CREATE SCHEMA MOI;
SET CURRENT SCHEMA MOI;
CREATE TABLE CITIZENS (
  CITIZEN_ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  FULL_NAME VARCHAR(120) NOT NULL,
  DATE_OF_BIRTH DATE NOT NULL,
  SEX CHAR(1) NOT NULL,
  BLOOD_TYPE CHAR(3),
  NATIONAL_ID VARCHAR(18) NOT NULL UNIQUE,
  MARITAL_STATUS VARCHAR(20)
);
CREATE TABLE RESIDENCY_PERMITS (
  PERMIT_ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CITIZEN_ID INTEGER NOT NULL REFERENCES MOI.CITIZENS(CITIZEN_ID),
  PERMIT_TYPE VARCHAR(30) NOT NULL,
  SPONSOR_NAME VARCHAR(120),
  ISSUED_ON DATE NOT NULL,
  EXPIRES_ON DATE NOT NULL,
  STATUS VARCHAR(20) NOT NULL
);
CREATE TABLE VEHICLE_REGISTRATIONS (
  REG_ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CITIZEN_ID INTEGER NOT NULL REFERENCES MOI.CITIZENS(CITIZEN_ID),
  PLATE VARCHAR(12) NOT NULL UNIQUE,
  MAKE VARCHAR(40) NOT NULL,
  MODEL VARCHAR(60) NOT NULL,
  MODEL_YEAR INTEGER NOT NULL,
  INSURANCE_EXPIRES DATE
);
